param(
  # Folder containing the three runtime files. Defaults to dist\ next to this script.
  [string]$DistDir   = (Join-Path $PSScriptRoot "dist"),
  # Where to drop the generated .wxs and the final installer .msi.
  [string]$OutDir    = (Join-Path $PSScriptRoot "installer"),
  # Marketing version shown in Add/Remove Programs.
  [string]$Version   = "1.0.0",
  [string]$AppName   = "Ultralight IP CAM Viewer Recorder",
  [string]$Publisher = "Slava",
  # Stable UpgradeCode GUID. KEEP THIS THE SAME ACROSS RELEASES.
  [string]$UpgradeCode = "C5E7D9A1-3B4F-4D8E-9C12-2A3B4C5D6E7F",
  # Per-machine (Program Files, requires admin) or per-user (LocalAppData).
  [switch]$PerMachine
)

$ErrorActionPreference = "Stop"

# --- 1. Verify the three required runtime files are present ---------------
$required = @("Ultralight_IP_CAM_Viewer_Recorder.exe", "SDL2.dll", "libwinpthread-1.dll")
foreach ($f in $required) {
  $p = Join-Path $DistDir $f
  if (-not (Test-Path $p)) {
    throw "Missing: $p`nRun .\build_min_portable.ps1 first to produce the runtime files."
  }
}

# --- 2. Locate the already-installed WiX 7 --------------------------------
function Resolve-Wix {
  $candidates = @(
    "C:\Program Files\WiX Toolset v7.0\bin\wix.exe",
    "C:\Program Files\WiX Toolset v7.1\bin\wix.exe",
    "C:\Program Files (x86)\WiX Toolset v7.0\bin\wix.exe",
    "$env:USERPROFILE\.dotnet\tools\wix.exe",
    "$env:LOCALAPPDATA\Microsoft\dotnet\tools\wix.exe"
  )
  foreach ($c in $candidates) {
    if (Test-Path $c) { return $c }
  }
  $cmd = Get-Command wix.exe -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  return $null
}

$wix = Resolve-Wix
if (-not $wix) {
  throw @"
Could not find wix.exe. Expected at C:\Program Files\WiX Toolset v7.0\bin\wix.exe
(or any v7.x path). If you've moved/uninstalled it, point this script at the
right path or reinstall via winget: winget install WiXToolset.WiXCLI
"@
}
$wixVer = & $wix --version 2>$null
Write-Host "WiX: $wix (v$wixVer)" -ForegroundColor Cyan

# --- 3. OSMF EULA acceptance is passed as a build flag (see step 6) -------
# WiX 7+ requires the `-acceptEula <id>` flag on `wix build` (or the
# <AcceptEula> property in a .wixproj). The ID for the WiX-CLI EULA is
# "wix7"; see https://wixtoolset.org/osmf/ for the full table and the
# commercial-vs-community details.

# --- 4. Stage output directory --------------------------------------------
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

# --- 5. Generate the .wxs (WiX v4+ syntax — same dialect as WiX 5/6/7) ----
$scope = if ($PerMachine) { "perMachine" } else { "perUser" }

$xmlEscape = {
  param([string]$s)
  return $s.Replace('&','&amp;').Replace('<','&lt;').Replace('>','&gt;').Replace('"','&quot;')
}
$xAppName   = & $xmlEscape $AppName
$xPublisher = & $xmlEscape $Publisher

if ($PerMachine) {
  $installTree = @"
    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="INSTALLFOLDER" Name="$xAppName" />
    </StandardDirectory>
"@
} else {
  $installTree = @"
    <StandardDirectory Id="LocalAppDataFolder">
      <Directory Id="ProgramsFolder" Name="Programs">
        <Directory Id="INSTALLFOLDER" Name="$xAppName" />
      </Directory>
    </StandardDirectory>
"@
}
$startMenuDir = if ($PerMachine) { "ProgramMenu6432Folder" } else { "ProgramMenuFolder" }

$wxsPath = Join-Path $OutDir "installer.wxs"
$wxs = @"
<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by make_installer.ps1 — do not hand-edit; rerun the script. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package
      Name="$xAppName"
      Manufacturer="$xPublisher"
      Version="$Version"
      UpgradeCode="$UpgradeCode"
      Scope="$scope"
      Compressed="yes"
      InstallerVersion="500">

    <SummaryInformation Description="$xAppName installer" Manufacturer="$xPublisher" />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />
    <MajorUpgrade DowngradeErrorMessage="A newer version of $xAppName is already installed." />

$installTree
    <StandardDirectory Id="$startMenuDir">
      <Component Id="StartMenuShortcut" Guid="*">
        <Shortcut Id="StartMenuExe"
                  Name="$xAppName"
                  Description="$xAppName"
                  Target="[INSTALLFOLDER]Ultralight_IP_CAM_Viewer_Recorder.exe"
                  WorkingDirectory="INSTALLFOLDER"
                  Icon="AppIcon.exe" />
        <RemoveFolder Id="RemoveStartMenu" On="uninstall" />
        <RegistryValue Root="HKCU"
                       Key="Software\$xPublisher\$xAppName"
                       Name="installed" Type="integer" Value="1" KeyPath="yes" />
      </Component>
    </StandardDirectory>

    <Icon Id="AppIcon.exe" SourceFile="$DistDir\Ultralight_IP_CAM_Viewer_Recorder.exe" />
    <Property Id="ARPPRODUCTICON" Value="AppIcon.exe" />
    <Property Id="ARPNOMODIFY"   Value="1" />
    <Property Id="ARPNOREPAIR"   Value="1" />

    <Feature Id="Main" Title="$xAppName" Level="1">
      <ComponentGroupRef Id="RuntimeFiles" />
      <ComponentRef Id="StartMenuShortcut" />
    </Feature>

    <ComponentGroup Id="RuntimeFiles" Directory="INSTALLFOLDER">
      <Component Id="MainExe" Guid="*">
        <File Id="MainExeFile"
              Source="$DistDir\Ultralight_IP_CAM_Viewer_Recorder.exe"
              KeyPath="yes" />
      </Component>
      <Component Id="SDL2Dll" Guid="*">
        <File Id="SDL2DllFile" Source="$DistDir\SDL2.dll" KeyPath="yes" />
      </Component>
      <Component Id="PthreadDll" Guid="*">
        <File Id="PthreadDllFile"
              Name="libwinpthread-1.dll"
              Source="$DistDir\libwinpthread-1.dll"
              KeyPath="yes" />
      </Component>
    </ComponentGroup>
  </Package>
</Wix>
"@
Set-Content -Path $wxsPath -Value $wxs -Encoding UTF8
Write-Host "Wrote: $wxsPath ($scope install)" -ForegroundColor Cyan

# --- 6. Build the MSI -----------------------------------------------------
$msiPath = Join-Path $OutDir ("Ultralight_IP_CAM_Viewer_Recorder_" + $Version + ".msi")
if (Test-Path $msiPath) { Remove-Item -Force $msiPath }

Write-Host "Compiling MSI..." -ForegroundColor Cyan
& $wix build -acceptEula wix7 -arch x64 -out $msiPath $wxsPath
if ($LASTEXITCODE -ne 0) {
  throw "WiX build failed (exit $LASTEXITCODE). See output above for details."
}

if (-not (Test-Path $msiPath)) { throw "Expected MSI not produced: $msiPath" }
$sizeMB = [math]::Round((Get-Item $msiPath).Length / 1MB, 2)

# Clean up the intermediate .wixpdb.
Remove-Item -Force -ErrorAction SilentlyContinue ([System.IO.Path]::ChangeExtension($msiPath, ".wixpdb"))

Write-Host ""
Write-Host "MSI ready:" -ForegroundColor Green
Write-Host "  $msiPath ($sizeMB MB)" -ForegroundColor Green
Write-Host ""
Write-Host "Install:    msiexec /i `"$msiPath`"" -ForegroundColor DarkGray
Write-Host "Silent:     msiexec /i `"$msiPath`" /qn /norestart" -ForegroundColor DarkGray
Write-Host "Uninstall:  msiexec /x `"$msiPath`"" -ForegroundColor DarkGray
Write-Host "Sign:       signtool sign /a /tr http://timestamp.digicert.com /td sha256 /fd sha256 `"$msiPath`"" -ForegroundColor DarkGray
if (-not $PerMachine) {
  Write-Host ""
  Write-Host "Per-user install -> %LocalAppData%\Programs\$AppName, no UAC prompt." -ForegroundColor DarkGray
  Write-Host "For enterprise/GPO-deployable per-machine MSI, rerun with -PerMachine." -ForegroundColor DarkGray
}
